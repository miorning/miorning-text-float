'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
const {artifacts,browserOptions,sanitize}=require('./runtime.cjs');
const root=path.resolve(__dirname,'..');
const version=JSON.parse(fs.readFileSync(path.join(root,'extension/manifest.json'),'utf8')).version;
const preview=path.join(root,'dist',`MiorningTextFloat-v${version}`,'preview.html');
const report={version,scope:'Packaged standalone preview; local isolated browser only',checks:[],pageErrors:[]};
let browser;
(async()=>{
  assert.ok(fs.existsSync(preview),'Run npm run package first');
  browser=await chromium.launch({...browserOptions(chromium),headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  page.on('pageerror',error=>report.pageErrors.push(error.message));
  await page.goto(pathToFileURL(preview).href);
  assert.equal(await page.evaluate(()=>MiorningTextFloat.version),version);await page.evaluate(()=>MiorningTextFloat.whenIdle());
  report.checks.push('Packaged runtime version matches manifest');
  await page.waitForFunction(()=>document.querySelector('.miorning-text-float-dock')?.shadowRoot.querySelector('img').naturalWidth===128);
  const dock=page.locator('.miorning-text-float-dock');
  assert.equal(await dock.getAttribute('data-expanded'),'false');
  await dock.locator('.launcher').hover();assert.equal(await dock.getAttribute('data-expanded'),'true');
  await page.mouse.move(40,40);assert.equal(await dock.getAttribute('data-expanded'),'false');
  report.checks.push('Embedded transparent cat plaque reveals fully on hover and retracts');
  await page.locator('#fixture-textarea').click();await page.evaluate(()=>MiorningTextFloat.whenIdle());
  await page.waitForFunction(()=>document.querySelector('.miorning-text-float-shell').shadowRoot.querySelector('.logo').naturalWidth>0);
  report.checks.push('Embedded cat logo loads without external files');
  await page.getByRole('button',{name:'夜间模式',exact:true}).click();
  assert.equal(await page.locator('#fixture-textarea').evaluate(el=>getComputedStyle(el).colorScheme),'dark');
  await page.getByRole('spinbutton',{name:'字体大小',exact:true}).click();
  await page.getByRole('slider',{name:'滑动调整字号'}).fill('64');
  await page.getByRole('button',{name:'关闭字号滑块',exact:true}).click();
  assert.equal(await page.locator('#fixture-textarea').evaluate(el=>getComputedStyle(el).fontSize),'64px');
  report.checks.push('Theme and font slider work in bundled preview');
  await page.locator('#fixture-textarea').fill('打包验证\nEsc 确认');await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!MiorningTextFloat.getState().open);
  assert.equal(await page.locator('#fixture-textarea').inputValue(),'打包验证\nEsc 确认');
  await page.locator('#fixture-textarea').click();await page.evaluate(()=>MiorningTextFloat.whenIdle());
  assert.equal(await page.evaluate(()=>MiorningTextFloat.getState().theme),'dark');
  assert.equal(await page.evaluate(()=>MiorningTextFloat.getState().fontSize),64);
  report.checks.push('Esc saves multiline text and persisted preferences reopen');
  await page.screenshot({path:path.join(artifacts,'v030-package-preview.png')});
  assert.equal(await page.evaluate(()=>fixtureState().counts.generation),0);
  assert.equal(report.pageErrors.length,0,JSON.stringify(report.pageErrors));
  report.checks.push('No generation and no browser errors');
  report.status='passed';
})().catch(error=>{report.status='failed';report.error=sanitize(error.stack);process.exitCode=1;}).finally(async()=>{
  await browser?.close();fs.writeFileSync(path.join(artifacts,'v030-package-report.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
});
